// Generates references/state-baseline.md from scripts/lib/component-states.mjs.
// The table is the one list of which components owe which interaction states:
// `verify:check` reads the module, and `figma-executor` (which cannot import
// JavaScript) reads this rendering. Mirrors build-native-adapter-config.mjs:
// run bare to write, --check to gate CI. Zero dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ARCHETYPES, BASELINE_STATES, NAME_SYNONYMS, STATE_SYNONYMS } from './lib/component-states.mjs';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(REPO_ROOT, 'references', 'state-baseline.md');

export function render(states = BASELINE_STATES, synonyms = NAME_SYNONYMS, archetypes = ARCHETYPES, stateSynonyms = STATE_SYNONYMS) {
  const aliases = Object.keys(stateSynonyms).map((s) => `\`${s}\` counts as \`${stateSynonyms[s]}\``).join(', and ');
  const owing = archetypes.filter((a) => (states[a] ?? []).length > 0);
  const rows = owing.map((a) => {
    const names = Object.keys(synonyms).filter((n) => synonyms[n] === a);
    return `| ${a} | ${names.map((n) => `\`${n}\``).join(', ')} | ${states[a].map((s) => `\`${s}\``).join(', ')} |`;
  });
  const exempt = archetypes.filter((a) => !owing.includes(a) && a !== 'other');
  const exemptNames = exempt.flatMap((a) => Object.keys(synonyms).filter((n) => synonyms[n] === a));
  return `<!-- GENERATED by scripts/build-state-baseline.mjs from scripts/lib/component-states.mjs. Do not edit; run: node scripts/build-state-baseline.mjs -->
# State baseline

Which interaction states a component owes. This is the one list both checks read:
\`verify:check\` (\`state-incomplete\`) reads it from \`scripts/lib/component-states.mjs\`,
and \`figma-executor\` (its state check and the \`focus-indicator\` check) reads
this table. CI fails when the table is stale.

A component name matches a row when it folds (lowercase, punctuation and spaces
stripped) to exactly one of that row's names. \`Text Field\` folds to \`textfield\`.
Matching is exact on purpose: \`IconButton\` matches nothing, and a component that
matches nothing owes no states.

| Archetype | Names | States owed |
|---|---|---|
${rows.join('\n')}

Every state in the table must be a value on the component's \`state\` axis. On the
Figma side the matrix also carries \`default\` as the resting state; the CLI does not
count it. ${aliases}, since that is what shadcn and Radix call it. Conditional states (\`loading\`, \`error\`, \`success\`) are not in the table:
whether one applies is a design judgment.

Names that fold to ${exemptNames.map((n) => `\`${n}\``).join(', ')} owe none, so neither check asserts states on them.
`;
}

function main() {
  const check = process.argv.includes('--check');
  const rendered = render();
  if (!check) {
    writeFileSync(OUT, rendered);
    console.log(`wrote ${OUT}`);
    return;
  }
  const current = readFileSync(OUT, 'utf8');
  if (current === rendered) {
    console.log('references/state-baseline.md is up to date');
    return;
  }
  console.error(
    'references/state-baseline.md is stale.\n' +
      'Run: node scripts/build-state-baseline.mjs',
  );
  process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
